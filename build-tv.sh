#!/usr/bin/env bash
# Linux / macOS version of build-tv.ps1: packages Reelhouse as a signed .wgt, with the server addresses and keys
# from .env built in, and installs it on a Samsung TV in Developer Mode.
#
#   ./build-tv.sh <tv-ip>          # build, install and launch
#   ./build-tv.sh --no-install     # only build .buildResult/Reelhouse.wgt
#
# Needs:
#   - the Tizen Studio CLI (TIZEN_HOME, default ~/tizen-studio);
#   - a JDK 11+ for signing (JAVA, default ~/.local/jdk-17/bin/java, else `java`);
#   - your Samsung certificates in CERT_DIR (default ~/SamsungCertificate/MediaLoader): author.p12 and
#     distributor.p12. Their passwords come from TIZEN_AUTHOR_PASSWORD / TIZEN_DISTRIBUTOR_PASSWORD in .env or the
#     environment, else you're asked for them.
#
# The TV only accepts installs from the computer set as "Host PC IP" in its Developer Mode.
set -euo pipefail

root="$(cd "$(dirname "$0")" && pwd)"
app_id='MdLoader01.MediaLoader'
TIZEN_HOME="${TIZEN_HOME:-$HOME/tizen-studio}"
CERT_DIR="${CERT_DIR:-$HOME/SamsungCertificate/MediaLoader}"
tizen="$TIZEN_HOME/tools/ide/bin/tizen"
sdb="$TIZEN_HOME/tools/sdb"

tv_ip=''
install=1
for arg in "$@"; do
    case "$arg" in
        --no-install) install=0 ;;
        -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
        *) tv_ip="$arg" ;;
    esac
done
[ -x "$tizen" ] || { echo "error: Tizen CLI not found at $tizen (set TIZEN_HOME)" >&2; exit 1; }
if [ "$install" = 1 ] && [ -z "$tv_ip" ]; then echo "error: give the TV's IP address, or --no-install" >&2; exit 1; fi
for f in author.p12 distributor.p12; do
    [ -f "$CERT_DIR/$f" ] || { echo "error: $CERT_DIR/$f not found (copy your Samsung certificates there, or set CERT_DIR)" >&2; exit 1; }
done
if [ -z "${JAVA:-}" ] && [ -x "$HOME/.local/jdk-17/bin/java" ]; then export JAVA="$HOME/.local/jdk-17/bin/java"; fi

# ---- 1. Stage only the app files ----
stage="$root/.buildResult"
rm -rf "$stage"
mkdir -p "$stage"
cp -r "$root/config.xml" "$root/index.html" "$root/icon.png" "$root/css" "$root/js" "$stage/"
if [ -d "$root/img" ]; then cp -r "$root/img" "$stage/"; fi
echo "Staged app files in $stage"

# ---- 2. Server addresses and keys from .env into the packaged js/config.js (the source copy stays key-free) ----
declare -A env=()
if [ -f "$root/.env" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
        line="${line%$'\r'}"
        if [[ "$line" =~ ^[[:space:]]*([A-Z_]+)[[:space:]]*=[[:space:]]*(.*[^[:space:]])?[[:space:]]*$ ]]; then
            env["${BASH_REMATCH[1]}"]="${BASH_REMATCH[2]:-}"
        fi
    done < "$root/.env"
    val() { local v="${env[$1]:-}"; printf '%s' "${v:-$2}"; }
    js() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e "s/'/\\\\'/g"; }      # for a '...' JavaScript string
    cat > "$stage/js/config.js" <<EOF
/* Generated by build-tv.sh from .env */
var MEDIALOADER_DEFAULTS = {
    tv:    { url: '$(js "$(val SONARR_URL http://media-server:8989)")', apiKey: '$(js "$(val SONARR_API_KEY '')")', qualityProfile: '$(js "$(val SONARR_QUALITY_PROFILE HD-1080p)")' },
    movie: { url: '$(js "$(val RADARR_URL http://media-server:7878)")', apiKey: '$(js "$(val RADARR_API_KEY '')")', qualityProfile: '$(js "$(val RADARR_QUALITY_PROFILE 'Low Quality 1080')")' },
    music: { url: '$(js "$(val LIDARR_URL http://media-server:8686)")', apiKey: '$(js "$(val LIDARR_API_KEY '')")', qualityProfile: '$(js "$(val LIDARR_QUALITY_PROFILE '')")' }
};
var MEDIALOADER_PLEX = { url: '$(js "$(val PLEX_URL 'http://<plex-server-ip>:32400')")', token: '$(js "$(val PLEX_TOKEN '')")' };
var MEDIALOADER_TMDB = { token: '$(js "$(val TMDB_TOKEN '')")' };
EOF
    missing=''
    for k in SONARR_API_KEY RADARR_API_KEY LIDARR_API_KEY; do [ -n "${env[$k]:-}" ] || missing="$missing $k"; done
    if [ -n "$missing" ]; then echo "warning: no value in .env for:$missing (you can enter them on the TV in Settings)" >&2
    else echo 'API keys from .env written into the package.'; fi
else
    echo 'warning: no .env found: the package uses js/config.js as-is' >&2
fi

# ---- 3. Sign and package (tools/package-tv.sh) ----
AUTHOR_PASSWORD="${TIZEN_AUTHOR_PASSWORD:-${env[TIZEN_AUTHOR_PASSWORD]:-}}"
DISTRIBUTOR_PASSWORD="${TIZEN_DISTRIBUTOR_PASSWORD:-${env[TIZEN_DISTRIBUTOR_PASSWORD]:-}}"
if [ -z "$AUTHOR_PASSWORD" ]; then read -r -s -p 'Author certificate password: ' AUTHOR_PASSWORD; echo; fi
if [ -z "$DISTRIBUTOR_PASSWORD" ]; then read -r -s -p 'Distributor certificate password (Enter: same): ' DISTRIBUTOR_PASSWORD; echo; fi
DISTRIBUTOR_PASSWORD="${DISTRIBUTOR_PASSWORD:-$AUTHOR_PASSWORD}"
echo 'Signing with your Samsung certificate...'
AUTHOR_P12="$CERT_DIR/author.p12" DISTRIBUTOR_P12="$CERT_DIR/distributor.p12" \
    AUTHOR_PASSWORD="$AUTHOR_PASSWORD" DISTRIBUTOR_PASSWORD="$DISTRIBUTOR_PASSWORD" \
    APP_DIR="$stage" TIZEN_HOME="$TIZEN_HOME" bash "$root/tools/package-tv.sh" "$stage" | grep -v '^Built '
wgt="$stage/Reelhouse.wgt"
[ -f "$wgt" ] || { echo "error: no .wgt was produced" >&2; exit 1; }
echo "Built $wgt"
[ "$install" = 1 ] || exit 0

# ---- 4. Connect, install, launch ----
serial="$tv_ip:26101"
echo "Connecting to the TV at $serial..."
"$sdb" connect "$tv_ip" > /dev/null 2>&1 || true
if ! "$sdb" devices | grep -q "^$tv_ip:26101"; then
    echo "error: the TV didn't accept the connection. Check Developer Mode is on and its Host PC IP is this computer's IP, then hold the TV's power button to restart it." >&2
    exit 1
fi
# The CLI can fail and still exit 0, so its output is checked.
out="$("$tizen" install -n "$(basename "$wgt")" -s "$serial" -- "$stage" 2>&1 || true)"
if ! printf '%s' "$out" | grep -qi 'install completed\|Installed the package'; then
    printf '%s\n' "$out" | tail -8 >&2
    echo "error: install failed. A signature error usually means the TV's DUID isn't in your distributor certificate." >&2
    exit 1
fi
"$tizen" run -p "$app_id" -s "$serial" 2>&1 | tail -1
echo 'Installed and launched Reelhouse on the TV.'
