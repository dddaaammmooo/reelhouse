<#
.SYNOPSIS
  Packages MediaLoader as a signed .wgt and installs it on a Samsung TV in Developer Mode.

.DESCRIPTION
  1. Copies only the app files (config.xml, index.html, icon.png, css, js) into .buildResult
  2. Writes the API keys / server addresses from .env into the packaged js/config.js
     (so keys never need to be committed to the source config.js)
  3. Signs and packages with your Tizen Studio certificate profile
  4. Connects to the TV with sdb, installs and launches the app (skip with -NoInstall)

.EXAMPLE
  .\build-tv.ps1 -TvIp 192.168.1.50
  .\build-tv.ps1 -TvIp 192.168.1.50 -CertProfile MyTV -TizenHome D:\tizen-studio
  .\build-tv.ps1 -NoInstall          # just produce .buildResult\Reelhouse.wgt
#>
param(
    [string]$TvIp,
    [string]$CertProfile = 'MediaLoader',
    [string]$TizenHome = 'C:\tizen-studio',
    [switch]$NoInstall
)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$appId = 'MdLoader01.MediaLoader'

$tizen = Join-Path $TizenHome 'tools\ide\bin\tizen.bat'
$sdb = Join-Path $TizenHome 'tools\sdb.exe'
if (-not (Test-Path $tizen)) { throw "Tizen CLI not found at $tizen. Install Tizen Studio or pass -TizenHome." }
if (-not $NoInstall -and -not $TvIp) { throw 'Pass -TvIp <your TV''s IP address> (or -NoInstall to only build the package).' }

# ---- 1. Stage only the app files ----
$stage = Join-Path $root '.buildResult'
if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
New-Item -ItemType Directory $stage | Out-Null
Copy-Item (Join-Path $root 'config.xml'), (Join-Path $root 'index.html'), (Join-Path $root 'icon.png') -Destination $stage
Copy-Item (Join-Path $root 'css') -Destination $stage -Recurse
Copy-Item (Join-Path $root 'js') -Destination $stage -Recurse
if (Test-Path (Join-Path $root 'img')) { Copy-Item (Join-Path $root 'img') -Destination $stage -Recurse }
Write-Host "Staged app files in $stage"

# ---- 2. Bake server addresses and API keys from .env into the packaged config.js ----
$envFile = Join-Path $root '.env'
if (Test-Path $envFile) {
    $vals = @{}
    foreach ($line in Get-Content $envFile) {
        if ($line -match '^\s*([A-Z_]+)\s*=\s*(.*?)\s*$') { $vals[$Matches[1]] = $Matches[2] }
    }
    function Get-Val($name, $default) { if ($vals[$name]) { $vals[$name] } else { $default } }
    function Esc($s) { ($s -replace '\\', '\\\\') -replace "'", "\'" }
    $tv = @{ url = Get-Val 'SONARR_URL' 'http://media-server:8989'; key = Get-Val 'SONARR_API_KEY' ''; qp = Get-Val 'SONARR_QUALITY_PROFILE' 'HD-1080p' }
    $mv = @{ url = Get-Val 'RADARR_URL' 'http://media-server:7878'; key = Get-Val 'RADARR_API_KEY' ''; qp = Get-Val 'RADARR_QUALITY_PROFILE' 'Low Quality 1080' }
    $mu = @{ url = Get-Val 'LIDARR_URL' 'http://media-server:8686'; key = Get-Val 'LIDARR_API_KEY' ''; qp = Get-Val 'LIDARR_QUALITY_PROFILE' '' }
    $config = @"
/* Generated by build-tv.ps1 from .env */
var MEDIALOADER_DEFAULTS = {
    tv:    { url: '$(Esc $tv.url)', apiKey: '$(Esc $tv.key)', qualityProfile: '$(Esc $tv.qp)' },
    movie: { url: '$(Esc $mv.url)', apiKey: '$(Esc $mv.key)', qualityProfile: '$(Esc $mv.qp)' },
    music: { url: '$(Esc $mu.url)', apiKey: '$(Esc $mu.key)', qualityProfile: '$(Esc $mu.qp)' }
};
var MEDIALOADER_PLEX = { url: '$(Esc (Get-Val 'PLEX_URL' 'http://<plex-server-ip>:32400'))', token: '$(Esc (Get-Val 'PLEX_TOKEN' ''))' };
var MEDIALOADER_TMDB = { token: '$(Esc (Get-Val 'TMDB_TOKEN' ''))' };
"@
    Set-Content -Path (Join-Path $stage 'js\config.js') -Value $config -Encoding UTF8
    $missing = @('SONARR_API_KEY', 'RADARR_API_KEY', 'LIDARR_API_KEY') | Where-Object { -not $vals[$_] }
    if ($missing) { Write-Warning ("No value in .env for: " + ($missing -join ', ') + " (you can enter them on the TV in Settings).") }
    else { Write-Host 'API keys from .env written into the package.' }
} else {
    Write-Warning 'No .env found: the package uses js/config.js as-is.'
}

# ---- 3. Sign and package ----
Write-Host "Packaging with certificate profile '$CertProfile'..."
& $tizen package -t wgt -s $CertProfile -- $stage
if ($LASTEXITCODE -ne 0) { throw 'tizen package failed (check the certificate profile name in Certificate Manager).' }
$wgt = Get-ChildItem $stage -Filter *.wgt | Select-Object -First 1
if (-not $wgt) { throw 'No .wgt was produced.' }
Write-Host "Built $($wgt.FullName)"
if ($NoInstall) { return }

# ---- 4. Connect, install, launch ----
$serial = "$($TvIp):26101"
Write-Host "Connecting to the TV at $serial..."
& $sdb connect $TvIp | Out-Host
$devices = (& $sdb devices) -join "`n"
if ($devices -notmatch [regex]::Escape($TvIp)) {
    throw "The TV didn't accept the connection. Check Developer Mode is on and its Host PC IP is this PC's IP, then restart the TV."
}
& $tizen install -n $wgt.Name -s $serial -- $stage
if ($LASTEXITCODE -ne 0) { throw 'Install failed. A signature error usually means the TV''s DUID isn''t in your distributor certificate.' }
& $tizen run -p $appId -s $serial
Write-Host 'Installed and launched Reelhouse on the TV.'
